// EduTech "Card Values": card ID -> swizzle magic. Anything not listed uses 0x88.
const CARD_MAGIC: Record<number, number> = {
  0x6320: 0x11, 0x6302: 0x83, 0x6301: 0x88, 0x6300: 0x33, 0x2210: 0x16, 0x630b: 0x33, 0x6425: 0x88,
  0x6501: 0x34, 0x6511: 0x77, 0x6531: 0x77, 0x6512: 0x75, 0x6513: 0x99, 0x6514: 0x13, 0x651e: 0x60,
  0x6533: 0x60, 0x651f: 0x76, 0x6530: 0x10, 0x6532: 0x10, 0x6920: 0xa1, 0x6811: 0x77,
  0x690f: 0xa1, 0x6910: 0xa1, 0x6911: 0xa1, 0x6912: 0x88, 0x6930: 0x1a, 0x693f: 0x1a,
  0x7230: 0x10, 0x7235: 0x10, 0x7236: 0x10, 0x7430: 0x10, 0x7930: 0x10,
};

/**
 * The Card ID reply is a 32-bit value; on hardware (RDC6445-class, 2026-11-11) it read 0x65106510,
 * i.e. the 16-bit card code repeated. The table is keyed by that 16-bit code.
 */
export function cardCode(cardId: number): number {
  return cardId > 0xffff ? Math.floor(cardId / 0x10000) & 0xffff : cardId;
}

export function magicForCardId(cardId: number): number {
  return CARD_MAGIC[cardCode(cardId)] ?? 0x88;
}

